/**
 * Returns an inline SVG string for the requested Lucide icon.
 * Falls back to 'sparkles' if the icon is not recognized.
 */
export function getLucideIconSvg(name?: string, options: IconOptions = {}): string {
  const normalized = (name || 'sparkles').toLowerCase().trim().replace(/_/g, '-');
  const pathContent = ICONS[normalized] || ICONS.sparkles || '';
  const size = options.size ?? 24;
  const className = options.className ? ` class="${options.className}"` : '';

  return `<svg xmlns="http://www.w3.org/2000/svg" width="${size}" height="${size}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round"${className} aria-hidden="true">${pathContent.trim()}</svg>`;
}

