/**
 * REV-205: the section index of ../Revamp-docs, so agents read one section (a line range) instead of a whole document.
 * Pure: `scripts/docs-index.ts` reads the files and writes or checks INDEX.md.
 */

export interface DocSection {
  level: 2 | 3;
  title: string;
  /** 1-based line of the heading */
  start: number;
  /** 1-based last line of the section: before the next heading of the same or a higher level, else the last non-blank line */
  end: number;
}

/** A closing run of # counts only after a space, so "Why F#" keeps its # */
const HEADING = /^(#{2,3})\s+(.+?)(?:\s+#+)?\s*$/;
/** An opening fence and its info string; a closing fence is bare and at least as long, with the same character */
const FENCE = /^\s{0,3}(`{3,}|~{3,})(.*)$/;

export function docSections(text: string): DocSection[] {
  const lines = text.split('\n');
  let last = lines.length;
  while (last > 0 && lines[last - 1]!.trim() === '') last--;

  const found: { level: 2 | 3; title: string; start: number }[] = [];
  let fence: string | undefined;
  lines.forEach((line, i) => {
    const m = FENCE.exec(line);
    if (fence) {
      const closes = m && m[1]![0] === fence[0] && m[1]!.length >= fence.length && m[2]!.trim() === '';
      if (closes) fence = undefined;
      return;
    }
    if (m) {
      fence = m[1]!;
      return;
    }
    const heading = HEADING.exec(line);
    if (heading) found.push({ level: heading[1]!.length as 2 | 3, title: heading[2]!, start: i + 1 });
  });

  return found.map((section, i) => {
    const next = found.slice(i + 1).find((other) => other.level <= section.level);
    return { ...section, end: next ? next.start - 1 : last };
  });
}

export function buildDocsIndex(files: { name: string; text: string }[]): string {
  const blocks = files.map(({ name, text }) => {
    const items = docSections(text).map((s) => `${s.level === 3 ? '  ' : ''}- ${s.title}: ${s.start}-${s.end}`);
    return `## ${name}\n\n${items.join('\n')}\n`;
  });
  return (
    '# Revamp-docs Section Index\n\n' +
    'Generated by `npm run docs:index` in Revamp-dev (REV-205); do not edit by hand. Each entry is a heading and its line range: ' +
    'read only that range (for example `Read` with offset and limit) instead of the whole document.\n\n' +
    blocks.join('\n')
  );
}
